/**
 * Bundles the Vercel Serverless Function.
 *
 * server/vercel-entry.ts (and everything it imports, including src/data and
 * src/lib) is bundled into a single self-contained api/index.js. This keeps
 * Vercel's builder out of the business of resolving `.ts` import specifiers or
 * pulling in files from outside api/ — it just deploys plain JavaScript.
 *
 * Run by `npm run build`; the output is committed so the deploy never depends
 * on build ordering.
 */
import { build } from 'esbuild'

await build({
  entryPoints: ['server/vercel-entry.ts'],
  outfile: 'api/index.js',
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  // Runtime dependencies Vercel installs from package.json — no need to inline.
  external: ['express', 'nodemailer'],
  banner: { js: '// Generated by scripts/build-api.mjs — edit server/vercel-entry.ts instead.' },
  logLevel: 'info',
})
